// Persist the user's language choice across sessions.
const storedLanguage = localStorage.getItem('agriguard_language');
const initialLanguage = (storedLanguage || 'en').split('-')[0];

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLanguage,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false 
    }
  });

// Keep <html lang/dir> in sync (RTL support for Arabic).
function applyDocumentLanguage(lng) {
  const base = (lng || 'en').split('-')[0];
  document.documentElement.lang = base;
  document.documentElement.dir = base === 'ar' ? 'rtl' : 'ltr';
}

applyDocumentLanguage(i18n.language);

i18n.on('languageChanged', (lng) => {
  localStorage.setItem('agriguard_language', lng);
  applyDocumentLanguage(lng);
});

export default i18n;
